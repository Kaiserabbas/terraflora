/**
 * Quick CSV Export for the BOQ
 */
export function exportBOQToCSV(survey: SiteSurveyData, boqItems: BOQItem[]): void {
  const lines: string[] = [];
  lines.push(`"Item Code","Section","Category","Description","Specification","Quantity","Unit","Rate (${survey.currency})","Amount (${survey.currency})"`);

  for (const item of boqItems) {
    const desc = (item.description || '').replace(/"/g, '""');
    const spec = (item.specification || '').replace(/"/g, '""');
    const amount = (item.quantity * item.unitRate).toFixed(2);
    lines.push(`"${item.itemCode}","${item.section}","${item.category}","${desc}","${spec}","${item.quantity}","${item.unit}","${item.unitRate}","${amount}"`);
  }

  const csvContent = lines.join('\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `${survey.projectName.replace(/[^a-zA-Z0-9_-]/g, '_')}_BOQ.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
